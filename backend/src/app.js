import 'express-async-errors';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import path from 'node:path';
import { env } from './config/env.js';
import authRoutes from './routes/authRoutes.js';
import collectionRoutes from './routes/collectionRoutes.js';
import scanRoutes from './routes/scanRoutes.js';
import classifyRoutes from './routes/classifyRoutes.js';
import eventRoutes from './routes/eventRoutes.js';
import { errorHandler, notFound } from './middleware/error.js';

const app = express();
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({ origin: env.corsOrigin === '*' ? true : env.corsOrigin.split(',').map((item) => item.trim()), credentials: env.corsOrigin !== '*' }));
app.use(express.json({ limit: '1mb' }));
app.use(express.urlencoded({ extended: true, limit: '1mb' }));
app.use(morgan(env.nodeEnv === 'production' ? 'combined' : 'dev'));
app.use('/uploads', express.static(path.resolve(env.uploadDir), { maxAge: '1d', index: false }));
app.get('/health', (_req, res) => res.json({ success: true, data: { status: 'ok', service: 'waste-classification-api' } }));
app.use('/api/v1/auth', authRoutes);
app.use('/api/v1/collections', collectionRoutes);
app.use('/api/v1/scans', scanRoutes);
app.use('/api/v1/classify', classifyRoutes);
app.use('/api/v1/events', eventRoutes);
app.use(notFound);
app.use(errorHandler);
export default app;
